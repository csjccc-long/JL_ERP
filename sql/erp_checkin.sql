drop table if exists erp_checkin;
create table erp_checkin (
  checkin_id    bigint(20)   not null auto_increment  comment '打卡ID',
  user_id       bigint(20)   not null                 comment '用户ID',
  user_name     varchar(30)  not null                 comment '登录账号',
  checkin_date  date         not null                 comment '打卡日期',
  checkin_time  datetime     not null                 comment '打卡时刻',
  actions       int(11)      not null default 0       comment '当日动作数（登录与业务操作，用于热力强度）',
  source        varchar(10)  default 'manual'         comment '来源（manual 手动打卡 / seed 演示数据）',
  remark        varchar(255) default ''               comment '备注',
  create_time   datetime     default null,
  update_time   datetime     default null,
  primary key (checkin_id),
  unique key uk_checkin_user_date (user_id, checkin_date),
  key idx_checkin_user_time (user_id, checkin_time)
) engine=innodb auto_increment=1 comment='用户打卡记录';

