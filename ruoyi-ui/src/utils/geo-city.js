/** 去掉行政区划后缀，"深圳市" → "深圳" */
function bare(name) {
  return String(name || "")
    .replace(/特别行政区|自治区|自治州|地区|省|市|盟|县/g, "")
    .trim();
}

/**
 * 解析登录地点
 * @returns {{key: string, name: string, city: string, lat: number, lng: number, kind: 'intranet'|'city'|'unknown'}}
 */
export function resolveLoginLocation(raw) {
  const text = String(raw || "").trim();
  if (!text || text.startsWith("内网") || text === "局域网") {
    return { ...INTRANET_HUB, kind: "intranet" };
  }
  if (text === "XX XX" || text === "未知" || text === "-") {
    return { key: "unknown", name: "未知地区", city: "未知", lat: 34.3416, lng: 108.9398, kind: "unknown" };
  }

  // 兼容 "中国|0|广东省|深圳市|电信"、"广东省 深圳市"、"广东省深圳市"
  const parts = text
    .split(/[|\s]+/)
    .map((part) => part.trim())
    .filter((part) => part && !/^\d+$/.test(part) && part !== "中国" && part !== "0");

  const candidates = [];
  for (let i = parts.length - 1; i >= 0; i -= 1) {
    const piece = parts[i];
    // "广东省深圳市" 这种粘连串，优先切出市
    const glued = piece.match(/^(.+?[省市区县])?\s*(.+[市州盟])$/);
    if (glued && glued[2]) candidates.push(glued[2]);
    candidates.push(piece);
  }

  for (const candidate of candidates) {
    const city = bare(candidate);
    if (CITIES[city]) {
      return { key: city, name: city, city, lat: CITIES[city][0], lng: CITIES[city][1], kind: "city" };
    }
    const capital = PROVINCE_CAPITAL[city];
    if (capital && CITIES[capital]) {
      return {
        key: capital,
        name: capital,
        city: capital,
        lat: CITIES[capital][0],
        lng: CITIES[capital][1],
        kind: "city"
      };
    }
  }

  const label = parts[parts.length - 1] || text;
  return { key: bare(label) || "unknown", name: label, city: label, lat: 34.3416, lng: 108.9398, kind: "unknown" };
}
